// Скоринг v3 — откалиброван 2026-07-30 на расщеплённой выборке: веса подобраны по
// train (подачи 2016–2021), в скор вошли ТОЛЬКО компоненты, чей знак подтвердился на
// validation (2022+). Полная история калибровки: docs/КАЛИБРОВКА-V3.md.
//
// Честное ограничение: кросс-секционная дискриминация вне выборки слабая; скор
// ранжирует ОЖИДАНИЕ (хвостатое), а не вероятность успеха (она ~43% во всех корзинах).
// Главную работу делают гейты, скор — вторичная сортировка.
//
// Выброшено по итогам калибровки (эффект не воспроизвёлся на validation):
//   · ценовой контекст (просадка/максимум) — знак меняется с рыночным режимом;
//   · общий трек-рекорд по hit-rate прошлых покупок;
//   · «не покупал 3 года» (на validation знак отрицательный);
//   · положительные баллы за долларовый размер (сделки ≥$1M стабильно ХУЖЕ базы);
//   · «кратно крупнее обычной» (не проверяется устойчиво).
const rnd = (v, k = 4) => Math.round(v * 10 ** k) / 10 ** k;

// Роли, эффект на train/valid (12м, винзор, к базе выборки):
// F +8.4/+1.8, O +4.0/+5.4, D −0.2/+3.8, C −1.5/−6.7 (минус в ОБЕИХ половинах и во всех
// размерных корзинах), T +0.8/−5.2 (нестабильно), X −10.3/−5.3.
export const ROLE_ORDER = ['F', 'C', 'D', 'O', 'T', 'X'];
export const ROLE_POINTS = { F: 16, O: 16, D: 8, C: -8, T: 0, X: -12 };

export function topRole(rels) {
  for (const c of ROLE_ORDER) if (rels.some(x => (x ?? '').includes(c))) return c;
  return 'X';
}

// Прирост позиции: куплено / остаток до сделки. 9.99 = позиция открыта с нуля.
export function dOwnOf(r) {
  if (r.own === null || r.own === undefined || !r.sh) return null;
  const before = r.own - r.sh;
  return before > 0 ? rnd(r.sh / before) : (r.own === r.sh ? 9.99 : null);
}

export function scoreBuy({
  persons = 1,       // независимых физлиц в плотном ядре кластера (point-in-time для бэктеста)
  role = 'X',
  totalVal = 0,      // объём кластера (или сделки)
  val = 0,           // объём самой сделки
  dOwn = null,
  routine = null,    // true/false/null (null = истории меньше трёх лет)
  inflect = null,    // 'first-ever' | 'first-in-3y' | null
  windowOpen = 0,    // покупка в первую неделю после 10-Q/K
  aehN = null,       // прошлых ПРЕД-отчётных покупок с закрытым окном (Ali–Hirshleifer)
  aehHit = null,     // доля удачных среди них
} = {}) {
  const parts = {};

  // Кластер: на train +9.6% для ≥3, на validation ~0 (эффект концентрирован в 2020) —
  // вес сохранён из-за силы train и литературы, но урезан вдвое против v2.
  parts.cluster = persons >= 3 ? 20 : persons === 2 ? 8 : 0;

  parts.role = ROLE_POINTS[role] ?? -12;

  // Докупка: горб 5–50% подтверждён в обеих половинах (+3.3/+1.3 и +2.2/+5.2);
  // «позиция с нуля» стабильно отрицательна (−3.8/−4.0).
  parts.conviction = dOwn === null ? 0
    : dOwn >= 9 ? -12
    : dOwn >= 0.5 ? 4
    : dOwn >= 0.2 ? 16
    : dOwn >= 0.05 ? 10 : 0;

  // Крупные сделки ≥$1M хуже базы в обеих половинах (−2.1/−2.6): к моменту подачи уже в цене.
  parts.big = val >= 1e6 ? -8 : 0;

  // Классифицируемая нерутинность (есть ≥3 лет истории и паттерна нет): +6.0/+2.0.
  parts.history = routine === false ? 12 : 0;

  // Первая покупка в наших данных: +0.5/+7.9 (знак устойчив, величина нет — вес малый).
  parts.firstEver = inflect === 'first-ever' ? 8 : 0;

  // Покупка в первую неделю после отчёта: +3.0/+1.1 — реакция на свежую публичную
  // информацию, а не «рутинный window-open поток», как предполагалось в v2.
  parts.windowOpen = windowOpen ? 6 : 0;

  // Ali–Hirshleifer в нашей аппроксимации (профит прошлых покупок за ≤21 день до 10-Q/K):
  // работает только строгий порог n≥3 и hit≥60% (+2.4/+1.9); мягкий порог — ноль.
  parts.aeh = aehN !== null && aehN >= 3 && aehHit >= 0.6 ? 8 : 0;

  const total = Math.max(0, Math.min(100, Object.values(parts).reduce((a, b) => a + b, 0)));
  return { total, parts };
}

// Свежесть сигнала: множитель ранжирования скринера (не входит в скор).
export function freshness(daysSinceFiling) {
  if (daysSinceFiling === null || daysSinceFiling === undefined) return 1;
  if (daysSinceFiling <= 14) return 1;
  if (daysSinceFiling >= 180) return 0;
  return rnd(1 - (daysSinceFiling - 14) / 166, 3);
}
