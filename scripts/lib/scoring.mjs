// docs/КАЛИБРОВКА-V4.md; методика оценки — scripts/lib/portfolio.mjs.
//
// ПОЧЕМУ ПЕРЕСОБРАН. Скор v3 подбирался по средним ПО СДЕЛКАМ, а эта метрика смещена
// вверх (+5% на подставных данных, где сигнала нет) и неустойчива (расхождение оценки
// между половинами 15 п.п.). На портфельной проверке v3 не обгонял случайные веса:
// верхний квинтиль давал +3.2% на valid при том, что случайное взвешивание тех же
// признаков даёт до +4.7% в 95% случаев, — и был ОТРИЦАТЕЛЕН на train (−0.1%).
//
// КАК ПОДБИРАЛИСЬ ВЕСА. Не подгонкой. Регрессия, обученная на train, разворачивалась на
// valid со спреда +5.0 до −5.6 — переобучение плюс несовпадение цели (регрессия
// оптимизирует событийную доходность, а оценивается портфель). Поэтому в скор вошли
// только признаки с ДВОЙНЫМ основанием: опубликованный приор И устойчивый знак в обеих
// половинах наших измерений. Величины круглые и намеренно не настраивались: изменение
// любого веса на ±50% оставляет альфу верхнего квинтиля в диапазоне 7.1–10.4%.
//
// РЕЗУЛЬТАТ на held-out половине (2021+, ADV≥$3М, удержание 12 мес, альфа к рынку и
// наклону размера): верхний квинтиль +10.3% (t=2.75) против +3.2% у v3. Лестница по
// абсолютным порогам монотонна: 38+ → +6.2%, 28–37 → +5.5%, 18–27 → +1.2%,
// 8–17 → −1.4%, <8 → −5.3%. Превышает максимум из 200 случайных взвешиваний тех же
// признаков (10.0%). Ни один компонент не несёт результат в одиночку: при удалении
// любого остаётся +6.1…+8.5%.
//
// ЧЕСТНОЕ ОГРАНИЧЕНИЕ: отбор признаков опирался в том числе на аудит, считанный по всей
// выборке, поэтому valid для v4 не полностью «слепая». Чисто внешний ориентир — набор
// весов из одной литературы, без единого взгляда на наши данные: он даёт +6.1% (t=1.90).
// Настоящая ожидаемая величина скорее ближе к нему, чем к +10.3%.
//
// ВЫБРОШЕНО и почему:
//   · кластер (был +20) — альфа отрицательна в обеих половинах, −1.0% на 12 мес;
//   · трек-рекорд и признак Ali–Hirshleifer — УХУДШАЮТ результат (без трека +7.4 против
//     +6.1), к тому же известны лишь у 59% и 26% строк;
//   · прирост позиции (был +16 за докупку 20–50%) — после пересборки владения порядок
//     оказался обратным: докупка <5% даёт больше, чем ≥20%; сам горб не воспроизводится;
//   · штраф за сделки ≥$1М — знак неустойчив;
//   · «первая неделя после отчёта» — вне выборки не подтвердилась (train +3.2 / valid −0.6).
const rnd = (v, k = 4) => Math.round(v * 10 ** k) / 10 ** k;

// Роли. Приор: Wang/Shin/Francis 2012 (CFO информативнее CEO), Ravina & Sapienza 2010
// (независимые директора не хуже исполнительных). Наши измерения: D лучший (+2.4%/год,
// t=2.65 к вселенной), O отрицателен в ОБЕИХ половинах (−4.2/−1.4), X и T устойчиво
// отрицательны (−6…−8%/год). CEO не наказываем: штраф v3 знака не подтвердил.
export const ROLE_ORDER = ['F', 'C', 'D', 'O', 'T', 'X'];
export const ROLE_POINTS = { F: 10, D: 8, C: 0, O: -5, T: -10, X: -10 };
// Ниже этого дневного оборота эффект инсайдерских покупок исторически сильнее
// (Lakonishok & Lee 2001: 4% в малых против ~0 в крупных); подтверждено и у нас.
export const SMALL_ADV = 3e7;
// Порог близости к 52-недельному максимуму. Порог монотонен (≤2% даёт больше, чем ≤10%,
// тот больше, чем ≤20%) — подпись настоящего признака, а не подгонки под отсечку.
export const NEAR_HIGH = -0.05;

export function topRole(rels) {
  for (const c of ROLE_ORDER) if (rels.some(x => (x ?? '').includes(c))) return c;
  return 'X';
}

// Прирост позиции: куплено / остаток до сделки. 9.99 = позиция открыта с нуля.
//
// Остаток в Form 4 относится к форме владения (прямой пакет или конкретный косвенный),
// а не к лицу. У смешанной строки (di='M') сопоставим с покупкой только прямой пакет —
// берём его. Отрицательный остаток «до» арифметически невозможен для одной формы
// владения и означает, что остаток и покупка относятся к разным пакетам (у одного лица
// бывает несколько косвенных: траст, супруга, LLC — Form 4 не даёт им ключа).
// Такие строки честнее отдать как «неизвестно», чем как правдоподобное число.
export function dOwnOf(r) {
  const mixed = r.di === 'M';
  const sh = mixed ? r.shD : r.sh;
  const own = mixed ? r.ownD : r.own;
  if (own === null || own === undefined || !sh) return null;
  const before = own - sh;
  if (before < 0) return null;
  return before > 0 ? rnd(sh / before) : 9.99;
}

// Скор не зависит от того, что стало известно ПОСЛЕ подачи: все пять признаков берутся
// на дату сделки. Поэтому «живой» и point-in-time скор совпадают, и отдельная версия
// для бэктеста больше не нужна (в v3 они расходились из-за кластера).
export function scoreBuy({
  role = 'X',
  dd = null,         // просадка от 52-недельного максимума на дату сделки
  adv = null,        // медианный дневной $-оборот бумаги на дату сделки
  routine = null,    // true/false/null (null = истории меньше трёх лет, классификация неприменима)
  inflect = null,    // 'first-ever' | 'first-in-3y' | null
} = {}) {
  const parts = {};

  // Оппортунистическая сделка по Cohen–Malloy–Pomorski (2012): инсайдер с ≥3 годами
  // истории, НЕ торгующий в один и тот же календарный месяц из года в год. Крупнейший
  // вклад в скор: без него альфа верхнего квинтиля падает с +10.3% до +6.1%.
  // null (истории мало) намеренно даёт 0, а не половину: «неизвестно» ≠ «оппортунистическая».
  parts.oppo = routine === false ? 15 : 0;

  // Покупка вблизи 52-недельного максимума — сильнейший измеренный признак: инсайдер
  // платит высокую цену, и это редко бывает случайным. Отдельно проверено, что он даёт
  // прибавку СВЕРХ контроля из всех бумаг у максимума, то есть не сводится к моментуму.
  parts.near = dd !== null && dd >= NEAR_HIGH ? 15 : 0;

  parts.role = ROLE_POINTS[role] ?? -10;

  // Малые имена: эффект инсайдерских покупок исторически концентрирован именно там.
  parts.small = adv !== null && adv < SMALL_ADV ? 10 : 0;

  // Инфлексия: первая покупка этого лица в наших данных. Плюс в обеих половинах.
  parts.firstEver = inflect === 'first-ever' ? 8 : 0;

  // Верхняя граница шкалы — 58 (все компоненты сразу). Нижняя обрезка по нулю оставлена
  // ради совместимости отображения; сортировка от неё не страдает, потому что ниже нуля
  // оказывается лишь 1% строк.
  const total = Math.max(0, Math.min(100, Object.values(parts).reduce((a, b) => a + b, 0)));
  return { total, parts };
}
// Границы корзин скора для экрана «Статистика». Подобраны не на глаз: на held-out
// половине лестница по ним монотонна (38+ → +6.2%, 28–37 → +5.5%, 18–27 → +1.2%,
// 8–17 → −1.4%, <8 → −5.3% годовой альфы).
export const SCORE_CUTS = [38, 28, 18, 8];

// Свежесть сигнала: множитель ранжирования скринера (не входит в скор).
export function freshness(daysSinceFiling) {
  if (daysSinceFiling === null || daysSinceFiling === undefined) return 1;
  if (daysSinceFiling <= 14) return 1;
  if (daysSinceFiling >= 180) return 0;
  return rnd(1 - (daysSinceFiling - 14) / 166, 3);
}
